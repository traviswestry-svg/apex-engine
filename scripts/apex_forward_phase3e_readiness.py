"""Read-only Phase 3E readiness CLI. NEVER authorizes production activation."""
from __future__ import annotations
import argparse
import json
from pathlib import Path
from engine.forward_provenance_readiness import assess


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--evidence', help='Optional operator evidence-reference JSON; not trusted')
    p.add_argument('--operational-report', help='Optional existing Phase 3D JSON report')
    p.add_argument('--as-of', help='Optional timezone-aware ISO8601 time')
    args = p.parse_args()
    try:
        evidence = json.loads(Path(args.evidence).read_text()) if args.evidence else None
        op = json.loads(Path(args.operational_report).read_text()) if args.operational_report else None
        result = assess(evidence=evidence, operational_report=op, as_of=args.as_of)
    except (OSError, TypeError, ValueError, json.JSONDecodeError) as exc:
        result = assess()
        result['input_error'] = 'INPUT_' + type(exc).__name__
    print(json.dumps(result, indent=2, sort_keys=True))
    return 2  # Fail closed: no GO can be generated by this research tool.

if __name__ == '__main__':
    raise SystemExit(main())
